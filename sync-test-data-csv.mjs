import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const csvPath = path.join(rootDir, 'test data sheet.csv');
const outPath = path.join(rootDir, 'src', 'TestDataSheetCsv.js');
const packageJsonPath = path.join(rootDir, 'package.json');

const csvText = fs.readFileSync(csvPath, 'utf8').replace(/\r\n/g, '\n').replace(/\r/g, '\n');
const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
const versionStamp = String(packageJson.version || '').trim() || 'unknown';
const generatedAtIso = new Date().toISOString();
const output = `// Auto-generated by sync-test-data-csv.mjs from test data sheet.csv\nconst TEST_DATA_SHEET_CSV_VERSION = ${JSON.stringify(versionStamp)};\nconst TEST_DATA_SHEET_CSV_SYNCED_AT = ${JSON.stringify(generatedAtIso)};\nconst TEST_DATA_SHEET_CSV = ${JSON.stringify(csvText)};\n`;

fs.writeFileSync(outPath, output, 'utf8');
console.log(`Synced CSV test data to ${path.relative(rootDir, outPath)} (version ${versionStamp})`);
